import { createHash } from "node:crypto";
import {
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { migrations as currentWorkflowMigrations } from "../../../plugins/workflows/src/data.ts";

const FROZEN_BINDINGS = Object.freeze({
  architectureRevision: 2,
  serviceRevision: "bb-artifact-review-service:revision-1",
  v12ApprovalSha256:
    "c28b4884022b615491ba826ca6a6a2604d97c39b914d4ee44fdc406e30ea28e0",
  v12LedgerSha256:
    "ee24d026bffba3b976dfbc0363193459b0c7d98c22f362b2d9a18b01b0c1e1d7",
  v12ManifestSha256:
    "c074fc850151672da17f2b6478782a90becacef0a5641154c731033cb90a8a3b",
});
const EXPECTED_PLUGIN_ID = "workflows";
const EXPECTED_VECTOR_ENCODING =
  "id-colon-sha256-semicolon-no-terminal";
const FROZEN_V12_PATH = fileURLToPath(
  new URL(
    "../src/services/plugins/migration-authorities/workflows-artifact-review-recovery-v12.json",
    import.meta.url,
  ),
);
const CHECKED_IN_OUTPUT_PATH = fileURLToPath(
  new URL(
    "../src/services/plugins/generated/workflows-plugin-migration-authority.generated.ts",
    import.meta.url,
  ),
);

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function fail(message) {
  throw new Error(`F1_AUTHORITY_GENERATION_FAILED:${message}`);
}

function readFrozenAuthority() {
  const parsed = JSON.parse(readFileSync(FROZEN_V12_PATH, "utf8"));
  const authority = parsed?.authority;
  if (authority === null || typeof authority !== "object") {
    fail("missing-v12-authority");
  }
  if (!Array.isArray(authority.migrationCatalog)) {
    fail("missing-v12-migration-catalog");
  }
  const migrations = authority.migrationCatalog.map((candidate, index) => {
    if (
      candidate === null ||
      typeof candidate !== "object" ||
      candidate.id !== index ||
      typeof candidate.statementUtf8 !== "string" ||
      typeof candidate.byteLength !== "number" ||
      typeof candidate.sha256 !== "string"
    ) {
      fail(`invalid-v12-migration-row:${index}`);
    }
    const actualByteLength = Buffer.byteLength(candidate.statementUtf8, "utf8");
    const actualSha256 = sha256(candidate.statementUtf8);
    if (
      candidate.byteLength !== actualByteLength ||
      candidate.sha256 !== actualSha256
    ) {
      fail(`invalid-v12-migration-identity:${index}`);
    }
    return {
      id: candidate.id,
      byteLength: candidate.byteLength,
      sha256: candidate.sha256,
      statementUtf8: candidate.statementUtf8,
    };
  });
  if (migrations.length !== 23) {
    fail(`unexpected-v12-migration-count:${migrations.length}`);
  }

  const vectorValue = migrations
    .map((migration) => `${migration.id}:${migration.sha256}`)
    .join(";");
  const computedVector = {
    encoding: EXPECTED_VECTOR_ENCODING,
    byteLength: Buffer.byteLength(vectorValue, "utf8"),
    value: vectorValue,
    sha256: sha256(vectorValue),
  };
  const frozenVector = authority.migrationVectorIdentity;
  if (
    frozenVector === null ||
    typeof frozenVector !== "object" ||
    frozenVector.encoding !== computedVector.encoding ||
    frozenVector.byteLength !== computedVector.byteLength ||
    frozenVector.value !== computedVector.value ||
    frozenVector.sha256 !== computedVector.sha256
  ) {
    fail("invalid-v12-migration-vector");
  }

  return { migrations, migrationVector: computedVector };
}

function verifyCurrentWorkflowsSource(migrations) {
  if (currentWorkflowMigrations.length !== migrations.length) {
    fail(
      `current-workflows-count:${currentWorkflowMigrations.length}:${migrations.length}`,
    );
  }
  for (const [index, migration] of migrations.entries()) {
    const currentStatement = currentWorkflowMigrations[index];
    if (
      currentStatement !== migration.statementUtf8 ||
      Buffer.byteLength(currentStatement, "utf8") !== migration.byteLength ||
      sha256(currentStatement) !== migration.sha256
    ) {
      fail(`current-workflows-diverged:${index}`);
    }
  }
}

function renderGeneratedAuthority({ migrations, migrationVector }) {
  const renderedRows = JSON.stringify(migrations, null, 2);
  const renderedVector = JSON.stringify(migrationVector, null, 2);
  return `// Generated by scripts/generate-workflows-plugin-migration-authority.mjs.\n// Do not edit by hand.\n\nconst migrations = Object.freeze(\n  ${renderedRows}.map((migration) => Object.freeze(migration)),\n);\n\nexport const WORKFLOWS_PLUGIN_MIGRATION_AUTHORITY = Object.freeze({\n  architectureRevision: ${FROZEN_BINDINGS.architectureRevision},\n  serviceRevision: ${JSON.stringify(FROZEN_BINDINGS.serviceRevision)},\n  pluginId: ${JSON.stringify(EXPECTED_PLUGIN_ID)},\n  v12ManifestSha256: ${JSON.stringify(FROZEN_BINDINGS.v12ManifestSha256)},\n  v12ApprovalSha256: ${JSON.stringify(FROZEN_BINDINGS.v12ApprovalSha256)},\n  v12LedgerSha256: ${JSON.stringify(FROZEN_BINDINGS.v12LedgerSha256)},\n  migrations,\n  migrationVector: Object.freeze(${renderedVector}),\n});\n`;
}

function buildExpectedOutput() {
  const frozen = readFrozenAuthority();
  verifyCurrentWorkflowsSource(frozen.migrations);
  return renderGeneratedAuthority(frozen);
}

function writeGeneratedAuthority() {
  const expected = buildExpectedOutput();
  mkdirSync(dirname(CHECKED_IN_OUTPUT_PATH), { recursive: true });
  writeFileSync(CHECKED_IN_OUTPUT_PATH, expected, "utf8");
}

function verifyGeneratedAuthority() {
  const scratch = mkdtempSync(join(tmpdir(), "bb-f1-authority-verify-"));
  try {
    const temporaryOutput = join(scratch, "authority.generated.ts");
    writeFileSync(temporaryOutput, buildExpectedOutput(), "utf8");
    let checkedIn;
    try {
      checkedIn = readFileSync(CHECKED_IN_OUTPUT_PATH);
    } catch (error) {
      fail(`missing-checked-in-output:${error.code ?? "unknown"}`);
    }
    const temporary = readFileSync(temporaryOutput);
    if (!temporary.equals(checkedIn)) {
      fail("stale-checked-in-output");
    }
  } finally {
    rmSync(scratch, { recursive: true });
  }
}

const mode = process.argv[2];
if (mode === "--write") {
  writeGeneratedAuthority();
} else if (mode === "--verify") {
  verifyGeneratedAuthority();
} else {
  fail("usage:expected---write-or---verify");
}
